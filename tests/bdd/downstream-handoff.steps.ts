import assert from 'node:assert/strict';
import { Given, When, Then } from '@cucumber/cucumber';
import { LocalModel } from '../local-model-fixture.js';
import { historicalHandoff, claimHandoff, reportHandoff, sourceHandoffModel, citationHandoff, latestHandoffModel, protocolHandoffModel, staleHandoffModel, repairedHandoffModel, gapsHandoffModel, noMechanicalLoopModel, explicitRetryAfterDeliveryModel } from '../downstream-handoff-model-fixture.js';
import { unknownEffectsModel } from '../direct-map-delivery-model-fixture.js';
import { directMapEngineAcceptance } from '../direct-map-delivery-acceptance.js';
import type { SpecWorld } from './steps.js';
const runs = new WeakMap<SpecWorld, { m?: LocalModel; quote?: ReturnType<typeof citationHandoff>; done?: boolean; result?: unknown }>();
Given('当前候选交付前存在{string}', function(this: SpecWorld, history: string) { runs.set(this, { m: historicalHandoff(history) }); });
When('当前候选的下游检查全部通过', function(this: SpecWorld) {
 const run = runs.get(this)!;
 if(run.quote) assert(reportHandoff(run.quote.m,run.quote.check,run.quote.results).ok);
 else assert(reportHandoff(run.m!,claimHandoff(run.m!,'check')).ok);
});
Then('应发布当前候选并保留历史事实且不重复申报', function(this: SpecWorld) { assert.equal(runs.get(this)!.m!.c.outcome,'complete'); });
Given('负责人交付的文档来源声明与旧回执不一致', function(this: SpecWorld) { runs.set(this,{}); });
When('负责人提交当前报告', function(this: SpecWorld) { runs.get(this)!.result=sourceHandoffModel(); });
Then('应将原始声明和实际材料交给检查员且不要求来源修订', function(this: SpecWorld) { assert(runs.get(this)!.result); });
Given('检查员给当前候选附带{string}', function(this: SpecWorld, quote: string) { runs.set(this,{quote:citationHandoff(quote)}); });
Then('应一次采用检查结论且不追加引用核对', function(this: SpecWorld) { const m=runs.get(this)!.quote!.m; assert.equal(m.c.outcome,'complete'); assert.equal(m.c.usage.checks,1); });
const bind = (given: string, when: string, then: string, action: () => unknown) => {
 Given(given,function(this:SpecWorld){runs.set(this,{});});
 When(when,function(this:SpecWorld){runs.get(this)!.result=action();runs.get(this)!.done=true;});
 Then(then,function(this:SpecWorld){assert(runs.get(this)!.done);});
};
bind('当前候选保存过较早的失败结论和较新的通过结论','系统读取当前候选结论和产物验证状态','应展示最新通过结论且旧失败不再形成缺口',latestHandoffModel);
bind('当前任务仍存在未决宿主物理效果','负责人提交这份带未决效果的报告','不得重复执行或绕过实际效果结算',unknownEffectsModel);
bind('检查预算和重试预算均设为最大且检查响应缺少验收项','检查协议错误在技术补试后仍然存在','应明确结束检查且不再排队相同审核',protocolHandoffModel);
bind('用户更新要求后负责人已经提交新候选','旧检查尝试迟到返回通过','应拒绝旧结论并继续等待新候选检查',staleHandoffModel);
bind('当前报告遗漏用户要求且下游能够直接修正','检查员在当前工作提交修正正文产物和最终通过结论','应保留原稿并发布同一文档的下一修订且不重新派发负责人或检查',repairedHandoffModel);
bind('当前报告存在下游无法解决的问题','检查员返回该问题的最终失败结论','应在最终正文声明问题并正常交付且不得退回上游',gapsHandoffModel);
bind('任务预算均设为最大但负责人没有交付要求的文件','系统收到该提交','应声明文件缺失并正常交付且不重复派发负责人',noMechanicalLoopModel);
Given('真实模型链已经保存七个失败分片和一个成功分片',function(this:SpecWorld){runs.set(this,{});});
When('负责人正常交付且下游返回带非逐字引用的通过结论',async function(this:SpecWorld){runs.get(this)!.result=await directMapEngineAcceptance(true);});
Then('应通过原生适配器和数据库发布且没有重复审核请求',function(this:SpecWorld){assert(runs.get(this)!.result);});
Given('真实执行链交付的报告需要下游补充资料',function(this:SpecWorld){runs.set(this,{});});
When('检查员自行调用获准工具并提交修正稿',async function(this:SpecWorld){runs.get(this)!.result=await directMapEngineAcceptance(true,false,true);});
Then('应在同一检查工作完成工具执行和发布且没有上游回边',function(this:SpecWorld){assert(runs.get(this)!.result);});
const faults = new WeakMap<SpecWorld, string>();
Given('最大预算的检查服务返回{string}',function(this:SpecWorld,fault:string){runs.set(this,{});faults.set(this,fault);});
When('同一检查工作接收两次该错误响应',async function(this:SpecWorld){runs.get(this)!.result=await directMapEngineAcceptance(true,false,false,faults.get(this));});
Then('应明确结束协议错误且没有待执行审核或上游回退',function(this:SpecWorld){assert(runs.get(this)!.result);});
Given('检查员补救时已经实际读取并保存了网页资料',function(this:SpecWorld){runs.set(this,{});});
When('取得资料后的模型请求发生一次网络故障',async function(this:SpecWorld){runs.get(this)!.result=await directMapEngineAcceptance(true,false,true,undefined,true);});
Then('同一检查工作应复用已保存资料直接交付且不重复读取',function(this:SpecWorld){const result=runs.get(this)!.result;assert(result);this.attach(JSON.stringify(result),'application/json');});

Given('失败协助的缺口已经声明且原结果已经交付',function(this:SpecWorld){runs.set(this,{});});
When('用户明确重试这次失败协助',function(this:SpecWorld){runs.get(this)!.result=explicitRetryAfterDeliveryModel();});
Then('应保留旧交付并只响应这次用户操作且不自动回退',function(this:SpecWorld){assert(runs.get(this)!.result);});
