import { mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
mkdirSync('test-results', { recursive: true });
const gaps = JSON.parse(readFileSync('features/acceptance-gaps.json', 'utf8'));
const excluded = Object.keys(gaps).map(tag => `@${tag}`);
const tagArgs = excluded.length ? ['--tags', `not (${excluded.join(' or ')})`] : [];
const run = spawnSync(process.execPath, ['--import','tsx','node_modules/@cucumber/cucumber/bin/cucumber.js','features','--import','tests/bdd/*.ts',...tagArgs,'--format','progress','--format','json:test-results/cucumber.json'], { stdio: 'inherit', timeout: 60000, env: { ...process.env, TSX_TSCONFIG_PATH: 'tests/bdd/tsconfig.json' } });
if (run.error) console.error(run.error);
process.exit(run.status ?? 1);
